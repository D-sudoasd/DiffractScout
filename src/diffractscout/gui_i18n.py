def normalize_lang(lang: str | None) -> str:
    code = str(lang or DEFAULT_LANG).strip().lower()
    if code.startswith("zh"):
        return "zh"
    if code.startswith("en"):
        return "en"
    return DEFAULT_LANG


for _language, _help_messages in HELP_TEXT.items():
    STRINGS[_language].update(_help_messages)
REQUIRED_KEYS = REQUIRED_KEYS | frozenset(HELP_TEXT["zh"])


def t(lang: str | None, key: str, **fmt: object) -> str:
    """Look up a UI string; fall back to English then the key name."""

    code = normalize_lang(lang)
    table: Mapping[str, str] = STRINGS.get(code) or STRINGS[DEFAULT_LANG]
    text = table.get(key) or STRINGS["en"].get(key) or key
    if fmt:
        try:
            return text.format(**fmt)
        except (KeyError, ValueError):
            return text
    return text


def assert_language_parity() -> None:
    """Raise AssertionError if zh/en tables disagree on required keys."""

    for lang in SUPPORTED_LANGS:
        missing = REQUIRED_KEYS - set(STRINGS[lang])
        if missing:
            raise AssertionError(f"Language {lang!r} missing keys: {sorted(missing)}")
    zh_keys = set(STRINGS["zh"])
    en_keys = set(STRINGS["en"])
    if zh_keys != en_keys:
        raise AssertionError(
            f"zh/en key mismatch: only_zh={sorted(zh_keys - en_keys)} "
            f"only_en={sorted(en_keys - zh_keys)}"
        )
